#!/usr/bin/env python3
"""**過去の在籍を復元するときの、数え方の正本。**

**測る前に決める。** あとから決めると、**都合のいい数え方を選べてしまう。**
（`floor_kumu.py` の「合っていた／直した／落とした／作った」と同じ理由）

ここには**数え方だけ**を置く。**取りに行かないし、判定もしない。**

## 判定は3つ。**「見つからない」を「不在」にしない**

    在籍を確認できた      その時点にそこに在った、と一次情報で言える
    不在を確認できた      その時点にそこに無かった、と一次情報で言える
    どちらも確認できない  **見つからなかった。それだけ**

**3つ目を「不在」に寄せない。** 寄せた瞬間、**沈黙が証拠になる。**

2026-09-21 に決めた。理由——**リリースに書かれるのは「変化」であって「在籍」ではない。**
10年いる店はどこにも出てこない。**出てこないことは、無かったことではない。**

## 分母を2つに分ける

**「いた」と「いなかった」を1つの割合にしない。**

    在籍の確認できた率 = 在籍を確認できた ÷ （在籍を確認できた + どちらも確認できない）
    不在の確認できた率 = 不在を確認できた ÷ （不在を確認できた + どちらも確認できない）

**「無かったことの証明」は、あることの証明より難しい。**
一緒に数えると、**復元率が「いたが取れた割合」に見える。**

## 出どころは5つ。**一次と二次を混ぜない**

    施設ショップガイド    施設自身の現在一覧。**過去は残らないことがある**
    運営会社一次発表      運営会社のニュースリリース。**発表主体が当事者**
    テナント企業一次発表  その会社自身のニュース。**発表主体が当事者**
    行政一次情報          許認可の一覧・届出。**日付が制度で付く**
    第三者報道            業界メディア・地域メディア。**日付は書いてあるが伝聞**

**最後の1つだけ性質が違う。** 分けずに数えると、**伝聞が一次情報の顔をする。**

## 片道だけ問題

    開店日だけ分かる  → 「**その日以降いた**」しか言えない
    閉店日だけ分かる  → 「**その日まではいた**」しか言えない
    両方あって初めて  → **区間が確定する**

大規模小売店舗立地法で既に踏んだ形（新設・変更・廃止が揃うのは 2,262棟中17棟）。
**テナント単位でも同じことが起きる。** 片側しか無いものを、区間が分かったことにしない。

## 検索結果の存在から、営業時点を推定しない

**「検索に出た」は「その日に在った」ではない。**
根拠にしてよいのは、**出どころが書いた日付**だけ。
"""

# 判定。**この3つ以外を作らない**
HANTEI = ("在籍を確認できた", "不在を確認できた", "どちらも確認できない")

# 出どころ。**一次と二次を分ける**
DEDOKORO = (
    ("shisetsu-guide", "施設ショップガイド", "一次"),
    ("unei-happyo",    "運営会社一次発表",   "一次"),
    ("tenanto-happyo", "テナント企業一次発表", "一次"),
    ("gyosei",         "行政一次情報",       "一次"),
    ("hodo",           "第三者報道",         "**二次**"),
)

# 区間の分かり方。**片側だけを、区間が分かったことにしない**
KUKAN = ("開いた日だけ", "閉じた日だけ", "両方", "どちらも無い")


def kazoeru(hantei_ra):
    """判定の一覧から数える。**分母を2つに分ける。**

    `hantei_ra` は `HANTEI` の文字の並び。
    """
    from collections import Counter
    c = Counter(hantei_ra)
    for h in c:
        if h not in HANTEI:
            raise ValueError(f"知らない判定: {h!r}。**3つ以外を作らない**")
    zai, fu = c["在籍を確認できた"], c["不在を確認できた"]
    nashi = c["どちらも確認できない"]
    return {
        "在籍を確認できた": zai,
        "不在を確認できた": fu,
        "どちらも確認できない": nashi,
        # **別々の分母。** 一緒にすると「いたが取れた割合」に見える
        "在籍の確認できた率": (zai / (zai + nashi)) if (zai + nashi) else None,
        "不在の確認できた率": (fu / (fu + nashi)) if (fu + nashi) else None,
        # **全体の1つの割合は出さない。** 出すと、上の2つが混ざる
    }


